#!/usr/bin/env python3
"""Interactive installer for LoseSound.

The script discovers a SoundTouch speaker on the LAN, writes ``.env`` and starts
the Docker Compose stack. It never changes a speaker unless ``--migrate`` is
given explicitly.
"""

from __future__ import annotations

import argparse
import concurrent.futures
import ipaddress
import json
import os
import socket
import subprocess
import sys
import time
import urllib.error
import urllib.parse
import urllib.request
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ENV_PATH = ROOT / ".env"

DEFAULTS = {
    "AFTERTOUCH_HTTP_PORT": "8091",
    "AFTERTOUCH_HTTPS_PORT": "8444",
    "PROXY_PORT": "8092",
    "SPEAKER_PORT": "8090",
}
OPTIONAL_KEYS = (
    "SPEAKER_IPS",
    "SPEAKER_PORT",
    "AFTERTOUCH_HTTP_PORT",
    "AFTERTOUCH_HTTPS_PORT",
    "PROXY_PORT",
    "BUFFER_SECONDS",
    "PREBUFFER_SECONDS",
    "BITRATE_KBPS",
    "RECONNECT_BACKOFF_MS",
    "AUDIO_PROXY_ENABLED",
    "DEFAULT_PRESET_MODE",
    "LOG_STREAM_CHUNKS",
    "RADIO_BROWSER_BASE_URL",
    "SOUNDTOUCH_VERSION",
    "LOSESOUND_VERSION",
    "API_TOKEN",
)


def log(message: str) -> None:
    print(message, flush=True)


# --------------------------------------------------------------------- .env
def read_env(path: Path) -> dict:
    values: dict[str, str] = {}
    if not path.exists():
        return values
    for line in path.read_text(encoding="utf-8").splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#") or "=" not in stripped:
            continue
        key, value = stripped.split("=", 1)
        values[key.strip()] = value.strip().strip('"').strip("'")
    return values


def write_env(path: Path, updates: dict[str, str]) -> None:
    """Update keys in place and keep comments and unknown keys."""
    lines = path.read_text(encoding="utf-8").splitlines() if path.exists() else ["# Generated by scripts/setup.py"]
    seen: set[str] = set()
    output: list[str] = []
    for line in lines:
        stripped = line.strip()
        if stripped and not stripped.startswith("#") and "=" in stripped:
            key = stripped.split("=", 1)[0].strip()
            if key in updates:
                output.append(f"{key}={updates[key]}")
                seen.add(key)
                continue
        output.append(line)
    for key, value in updates.items():
        if key not in seen and value:
            output.append(f"{key}={value}")
    path.write_text("\n".join(output).rstrip("\n") + "\n", encoding="utf-8")


# ------------------------------------------------------------------ network
def get_lan_ip() -> str:
    env_host = os.getenv("SERVICE_HOST")
    if env_host and env_host.lower() != "auto":
        return env_host
    try:
        with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as sock:
            sock.connect(("1.1.1.1", 80))
            return sock.getsockname()[0]
    except OSError:
        pass
    try:
        return socket.gethostbyname(socket.gethostname())
    except OSError:
        return "127.0.0.1"


def http_get(url: str, timeout: float = 2.0, method: str = "GET") -> bytes:
    request = urllib.request.Request(url, data=b"" if method == "POST" else None, method=method)
    request.add_header("User-Agent", "LoseSound-setup/1.0")
    with urllib.request.urlopen(request, timeout=timeout) as response:
        return response.read()


def http_json(url: str, timeout: float = 5.0) -> dict | None:
    try:
        return json.loads(http_get(url, timeout=timeout).decode("utf-8"))
    except (OSError, urllib.error.URLError, json.JSONDecodeError, UnicodeDecodeError):
        return None


def wait_for(url: str, timeout: float = 60.0) -> bool:
    deadline = time.time() + timeout
    while time.time() < deadline:
        try:
            http_get(url, timeout=2)
            return True
        except Exception:  # noqa: BLE001 - retry until deadline
            time.sleep(1)
    return False


# ------------------------------------------------------------- discovery
def local_text(root: ET.Element, name: str) -> str:
    wanted = name.lower()
    for node in root.iter():
        if node.tag.rsplit("}", 1)[-1].lower() == wanted and node.text:
            return node.text.strip()
    return ""


def parse_speaker_info(ip: str, body: bytes) -> dict | None:
    try:
        root = ET.fromstring(body)
    except ET.ParseError:
        return None
    text = body.decode("utf-8", errors="ignore")
    attrs = {key.lower(): value for key, value in root.attrib.items()}
    device_id = attrs.get("deviceid") or attrs.get("device_id") or attrs.get("id") or local_text(root, "deviceID")
    looks_like_soundtouch = (
        device_id or "SoundTouch" in text or "marge" in text.lower() or root.tag.lower().endswith("info")
    )
    if not looks_like_soundtouch:
        return None
    return {
        "ip": ip,
        "device_id": device_id or "",
        "name": attrs.get("name") or local_text(root, "name") or "SoundTouch",
        "type": attrs.get("type") or local_text(root, "type") or "",
        "marge_url": local_text(root, "margeURL"),
        "firmware": local_text(root, "softwareVersion"),
    }


def fetch_speaker(ip: str, timeout: float = 1.2, port: int = 8090) -> dict | None:
    try:
        body = http_get(f"http://{ip}:{port}/info", timeout=timeout)
    except (OSError, urllib.error.URLError, TimeoutError):
        return None
    return parse_speaker_info(ip, body)


def discover_ssdp(timeout: float = 2.0) -> set[str]:
    messages = ["ssdp:all", "urn:schemas-upnp-org:device:MediaRenderer:1"]
    hosts: set[str] = set()
    with socket.socket(socket.AF_INET, socket.SOCK_DGRAM, socket.IPPROTO_UDP) as sock:
        sock.settimeout(timeout)
        for search_target in messages:
            payload = "\r\n".join(
                [
                    "M-SEARCH * HTTP/1.1",
                    "HOST: 239.255.255.250:1900",
                    'MAN: "ssdp:discover"',
                    "MX: 1",
                    f"ST: {search_target}",
                    "",
                    "",
                ]
            ).encode("ascii")
            try:
                sock.sendto(payload, ("239.255.255.250", 1900))
            except OSError:
                continue
        deadline = time.time() + timeout
        while time.time() < deadline:
            try:
                data, address = sock.recvfrom(4096)
            except TimeoutError:
                break
            text = data.decode("iso-8859-1", errors="ignore")
            if "bose" in text.lower() or "soundtouch" in text.lower():
                hosts.add(address[0])
                continue
            for line in text.splitlines():
                if line.lower().startswith("location:"):
                    parsed = urllib.parse.urlparse(line.split(":", 1)[1].strip())
                    if parsed.hostname:
                        hosts.add(parsed.hostname)
    return hosts


def scan_subnet(local_ip: str) -> list[dict]:
    try:
        network = ipaddress.ip_network(f"{local_ip}/24", strict=False)
    except ValueError:
        return []
    hosts = [str(ip) for ip in network.hosts()]
    found: list[dict] = []
    with concurrent.futures.ThreadPoolExecutor(max_workers=48) as executor:
        futures = {executor.submit(fetch_speaker, ip, 0.45): ip for ip in hosts}
        for future in concurrent.futures.as_completed(futures):
            speaker = future.result()
            if speaker:
                found.append(speaker)
    return found


def discover_speakers(local_ip: str, explicit_ip: str | None = None) -> list[dict]:
    if explicit_ip and explicit_ip.lower() != "auto":
        speaker = fetch_speaker(explicit_ip, timeout=2)
        return (
            [speaker]
            if speaker
            else [
                {"ip": explicit_ip, "device_id": "", "name": "SoundTouch", "type": "", "marge_url": "", "firmware": ""}
            ]
        )

    candidates = set(discover_ssdp())
    by_ssdp = [speaker for speaker in (fetch_speaker(host, timeout=1.5) for host in sorted(candidates)) if speaker]
    if by_ssdp:
        return by_ssdp
    log("Kein Lautsprecher per SSDP gefunden, scanne lokales /24-Netz ...")
    return scan_subnet(local_ip)


def choose_speaker(speakers: list[dict]) -> dict:
    if not speakers:
        raise RuntimeError("Kein SoundTouch-Lautsprecher gefunden. Starte erneut mit --speaker-ip <IP>.")
    if len(speakers) == 1:
        return speakers[0]
    log("Mehrere SoundTouch-Lautsprecher gefunden:")
    for index, speaker in enumerate(speakers, start=1):
        log(f"  {index}. {speaker['ip']}  {speaker['name']} {speaker['type']}".strip())
    if not sys.stdin.isatty():
        raise RuntimeError("Mehrere Lautsprecher gefunden. Starte erneut mit --speaker-ip <IP>.")
    while True:
        selected = input("Nummer auswählen: ").strip()
        if selected.isdigit() and 1 <= int(selected) <= len(speakers):
            return speakers[int(selected) - 1]


# ------------------------------------------------------------------ docker
def docker_compose(*args: str, check: bool = True) -> subprocess.CompletedProcess:
    return subprocess.run(["docker", "compose", *args], cwd=ROOT, check=check)


def compose_up() -> None:
    log("Starte Docker Compose (Build inklusive) ...")
    docker_compose("up", "-d", "--build")


# --------------------------------------------------------------- migration
def http_post(url: str, timeout: float = 60.0) -> tuple[int, str]:
    request = urllib.request.Request(url, data=b"", method="POST")
    request.add_header("User-Agent", "LoseSound-setup/1.0")
    try:
        with urllib.request.urlopen(request, timeout=timeout) as response:
            return response.status, response.read().decode("utf-8", errors="replace")
    except urllib.error.HTTPError as exc:
        return exc.code, exc.read().decode("utf-8", errors="replace")
    except Exception as exc:  # noqa: BLE001 - returned to the caller
        return 0, str(exc)


def migrate_speaker(host: str, speaker: dict, env: dict, method: str = "xml") -> bool:
    port = env.get("AFTERTOUCH_HTTP_PORT", DEFAULTS["AFTERTOUCH_HTTP_PORT"])
    target = f"http://{host}:{port}"
    identifiers: list[str] = []
    for candidate in (speaker.get("device_id"), speaker.get("ip")):
        if candidate and candidate not in identifiers:
            identifiers.append(str(candidate))
    if not identifiers:
        log("Migration übersprungen: Lautsprecher hat weder IP noch deviceID.")
        return False

    log(f"Migriere {identifiers[0]} auf {target} (Methode {method}) ...")
    for device in identifiers:
        # Newer AfterTouch versions require a data sync before they migrate.
        sync_status, sync_body = http_post(f"{target}/setup/sync/{urllib.parse.quote(device)}", timeout=60)
        if sync_status == 200:
            log(f"Datensync für {device}: {sync_body[:120]}")
        elif sync_status:
            log(f"Datensync für {device} meldet HTTP {sync_status}: {sync_body[:120]}")

        query = urllib.parse.urlencode({"method": method, "target_url": target, "marge_url": target})
        url = f"{target}/setup/migrate/{urllib.parse.quote(device)}?{query}"
        status, body = http_post(url, timeout=90)
        if status == 200:
            try:
                payload = json.loads(body)
            except json.JSONDecodeError:
                payload = {}
            if payload.get("ok"):
                log("Migration wurde von AfterTouch bestätigt.")
                deadline = time.time() + 15
                while time.time() < deadline:
                    info = fetch_speaker(speaker["ip"], timeout=3)
                    if info and info.get("marge_url", "").rstrip("/") == target.rstrip("/"):
                        log("Migration bestätigt: margeURL zeigt auf AfterTouch.")
                        return True
                    time.sleep(1)
                log(
                    "Migration gesendet, aber margeURL noch nicht bestätigt. Prüfe den Speaker-Status im AfterTouch-UI."
                )
                return False
            log(f"Migration abgelehnt: {payload.get('message') or body[:200]}")

        if "device not found" in body.lower():
            continue
        if "migration data is not ready" in body.lower():
            log(
                "AfterTouch braucht zuerst einen Datensync; bitte im AfterTouch-UI 'Data Sync' ausführen und erneut versuchen."
            )
        else:
            log(f"Migration fehlgeschlagen: HTTP {status} {body[:250]}")
        log(f"Manuell: {url}")
        return False

    log("AfterTouch konnte den Lautsprecher weder über deviceID noch über IP finden.")
    return False


def print_findings(host: str, env: dict) -> None:
    port = env.get("PROXY_PORT", DEFAULTS["PROXY_PORT"])
    status = http_json(f"http://{host}:{port}/api/setup/status?refresh=1", timeout=20)
    if not status:
        log(f"Setup-Status nicht lesbar. Prüfe http://{host}:{port}/")
        return
    aftertouch = status.get("aftertouch") or {}
    log(f"AfterTouch: {aftertouch.get('version') or 'unbekannt'}")
    findings = status.get("findings") or []
    if not findings:
        log("Setup-Status: keine Befunde.")
    for finding in findings:
        log(f"  [{finding.get('severity', '?')}] {finding.get('message', '')}")
        if finding.get("hint"):
            log(f"          -> {finding['hint']}")


def run_verify(host: str) -> int:
    log("Führe Read-only-Prüfung aus ...")
    result = subprocess.run(
        [sys.executable, str(ROOT / "scripts" / "verify.py"), "--env-file", str(ENV_PATH), "--service-host", host],
        cwd=ROOT,
        check=False,
    )
    return result.returncode


# --------------------------------------------------------------------- main
def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="LoseSound Setup")
    parser.add_argument("--service-host", help="LAN IP of the Docker host")
    parser.add_argument("--speaker-ip", help="IP of the SoundTouch speaker")
    parser.add_argument("--no-start", action="store_true", help="only write .env, do not start Docker")
    parser.add_argument("--migrate", action="store_true", help="migrate the speaker to AfterTouch after start")
    parser.add_argument(
        "--method", default="xml", choices=["xml", "telnet", "resolv"], help="migration method (default: xml)"
    )
    parser.add_argument("--pull", action="store_true", help="pull the pinned container images before starting")
    parser.add_argument("--verify", action="store_true", help="run the read-only verification after start")
    args = parser.parse_args(argv)

    env = read_env(ENV_PATH)
    detected_host = get_lan_ip()
    if args.service_host:
        service_host = args.service_host
    elif env.get("SERVICE_HOST"):
        service_host = env["SERVICE_HOST"]
        if detected_host and detected_host != service_host:
            log(
                f"Hinweis: erkannte LAN-IP {detected_host} weicht von SERVICE_HOST={service_host} ab; behalte den bestehenden Wert."
            )
            log("         Mit --service-host <IP> kannst du ihn bewusst ändern.")
    else:
        service_host = detected_host
    log(f"Docker-Host-IP: {service_host}")

    speakers = discover_speakers(service_host, args.speaker_ip)
    if not speakers and env.get("SPEAKER_IP"):
        log("Nutze SPEAKER_IP aus bestehender .env als Fallback ...")
        speakers = discover_speakers(service_host, env["SPEAKER_IP"])
    speaker = choose_speaker(speakers)
    log(f"SoundTouch: {speaker['ip']} {speaker.get('name', '')}".strip())

    speaker_ips: list[str] = []
    for found in speakers:
        if found.get("ip") and found["ip"] not in speaker_ips:
            speaker_ips.append(found["ip"])

    updates = {"SERVICE_HOST": service_host, "SPEAKER_IP": speaker["ip"]}
    if len(speaker_ips) > 1:
        updates["SPEAKER_IPS"] = ",".join(speaker_ips)
    for key in OPTIONAL_KEYS:
        if key in env and env[key] and key not in updates:
            updates[key] = env[key]
    write_env(ENV_PATH, updates)
    log(f".env aktualisiert: {ENV_PATH}")

    if args.no_start:
        return 0

    if args.pull:
        log("Aktualisiere Container-Images ...")
        docker_compose("pull", check=False)

    compose_up()

    aftertouch_port = env.get("AFTERTOUCH_HTTP_PORT", DEFAULTS["AFTERTOUCH_HTTP_PORT"])
    proxy_port = env.get("PROXY_PORT", DEFAULTS["PROXY_PORT"])
    if not wait_for(f"http://{service_host}:{aftertouch_port}", timeout=90):
        log("AfterTouch war nach 90 Sekunden nicht erreichbar.")
        return 1
    log("AfterTouch ist erreichbar.")
    if not wait_for(f"http://{service_host}:{proxy_port}/api/health", timeout=60):
        log("LoseSound war nach 60 Sekunden nicht erreichbar. Prüfe 'docker compose logs preset-proxy'.")
        log("Hinweis: Bei einem bestehenden Daten-Volume muss es evtl. dem Container-Benutzer gehören:")
        log("  docker run --rm -v losesound_preset_proxy_data:/data busybox chown -R 10001:10001 /data")
        return 1

    if args.migrate:
        migrate_speaker(service_host, speaker, env, args.method)
    else:
        log("Migration übersprungen. Ohne AfterTouch-Migration funktionieren lokale Presets nicht zuverlässig.")
        log(f"AfterTouch UI: http://{service_host}:{aftertouch_port}")
        for found in speakers:
            if not found.get("device_id"):
                continue
            query = urllib.parse.urlencode({"target_url": f"http://{service_host}:{aftertouch_port}"})
            log(
                f"Migration {found.get('name', 'SoundTouch')} ({found['ip']}): http://{service_host}:{aftertouch_port}/setup/migrate/{found['device_id']}?{query}"
            )
        log(
            "Falls AfterTouch SSH verlangt: FAT-USB-Stick mit leerer Datei 'remote_services' einstecken und den Speaker neu starten."
        )

    print_findings(service_host, env)
    log(f"Preset UI: http://{service_host}:{proxy_port}")
    if args.verify:
        return run_verify(service_host)
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except KeyboardInterrupt:
        print()
        sys.exit(130)
    except Exception as exc:  # noqa: BLE001 - friendly top level error
        log(f"Fehler: {exc}")
        sys.exit(1)
